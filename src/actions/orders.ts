// Type for the order payload from frontend
export type CreateOrderPayload = {
    customer_id?: string | null;
    customer_email: string;
    customer_name: string;
    shipping_address: string;
    subtotal: number;
    discount: number;
    shipping_cost: number;
    // total is generated by DB
    payment_method: 'cod' | 'bank_transfer' | 'card' | 'jazzcash' | 'easypaisa';
    payment_status: 'pending' | 'paid' | 'failed';
    notes?: string | null;
    items: {
        product_id: string;
        product_name: string;
        product_image?: string | null;
        quantity: number;
        price_at_purchase: number;
        size?: string | null;
        color?: string | null;
    }[];
};

export async function createOrder(payload: CreateOrderPayload): Promise<ActionResult<{ orderId: string; orderNumber: string }>> {
    // 1. Rate limiting
    const rateCheck = await checkRateLimit('create-order', `ip-${payload.customer_email}`, RateLimits.mutation);
    if (!rateCheck.allowed) {
        return { success: false, error: `Too many attempts. Please try again in ${rateCheck.resetIn}s` };
    }

    try {
        const supabase = createAdminClient();

        // 2. Validate items stock (optional but recommended - skipping for now to keep it simple as per plan)

        // 3. Create Order
        // Note: 'total' is a generated column, so we omit it. 'order_number' is also likely generated or handled by DB trigger/default.
        const orderInsert: TablesInsert<'orders'> = {
            customer_id: payload.customer_id,
            customer_email: payload.customer_email, // Ensuring email is saved if schema supports it
            customer_name: payload.customer_name,
            shipping_address: payload.shipping_address,
            subtotal: payload.subtotal,
            discount: payload.discount,
            shipping_cost: payload.shipping_cost,
            total_amount: payload.subtotal + payload.shipping_cost - payload.discount, // Providing total_amount for the generated column source
            payment_method: payload.payment_method,
            payment_status: payload.payment_status,
            status: 'pending',
            notes: payload.notes
            // eslint-disable-next-line @typescript-eslint/no-explicit-any
        } as any;

        const { data: order, error: orderError } = await supabase
            .from('orders')
            .insert(orderInsert)
            .select()
            .single();

        if (orderError) {
            logger.error('Error creating order record', orderError, { payload });
            return { success: false, error: 'Failed to create order record' };
        }

        // 4. Create Order Items
        const orderItems = payload.items.map(item => ({
            order_id: order.id,
            product_id: item.product_id,
            product_name: item.product_name,
            product_image: item.product_image,
            quantity: item.quantity,
            price_at_purchase: item.price_at_purchase,
            size: item.size,
            color: item.color
        }));

        const { error: itemsError } = await supabase
            .from('order_items')
            .insert(orderItems);

        if (itemsError) {
            logger.error('Error creating order items', itemsError, { orderId: order.id });
            // Ideally we should rollback here, but Supabase HTTP API doesn't support transactions easily without RPC.
            // For now, we'll log it. Using createAdminClient improves reliability.
            return { success: false, error: 'Failed to add items to order' };
        }

        // 5. Send Confirmation Email (Fire and forget)
        // sendOrderConfirmation(order.id).catch(err => logger.error('Email failed', err));

        // 6. Loyalty Points (if customer exists)
        if (payload.customer_id) {
            // awardLoyaltyPoints(payload.customer_id, order.total_amount);
        }

        revalidatePath('/admin/orders');
        return { success: true, data: { orderId: order.id, orderNumber: order.order_number || order.id } };

    } catch (error) {
        logger.error('Unexpected error in createOrder', error);
        return { success: false, error: 'An unexpected error occurred processing your order' };
    }
}

export async function getRecentOrders(limit = 5) {
    const supabase = await createClient();
    const { data, error } = await supabase
        .from('orders')
        .select(`
            *,
            items:order_items(*)
        `)
        .order('created_at', { ascending: false })
        .limit(limit);

    if (error) {
        logger.error('Error fetching recent orders', error, { action: 'getRecentOrders' });
        return [];
    }

    return data;
}

export async function getOrders(page = 1, pageSize = 10, status?: string) {
    const supabase = await createClient();
    const from = (page - 1) * pageSize;
    const to = from + pageSize - 1;

    let query = supabase
        .from('orders')
        .select(`
            *,
            customer:customers(first_name, last_name)
        `, { count: 'exact' });

    if (status && status !== 'All') {
        const queryStatus = status.toLowerCase();
        if (['pending', 'packed', 'shipping', 'delivered', 'cancelled'].includes(queryStatus)) {
            query = query.eq('status', queryStatus as "pending" | "packed" | "shipping" | "delivered" | "cancelled");
        }
    }

    const { data, error, count } = await query
        .order('created_at', { ascending: false })
        .range(from, to);

    if (error) {
        logger.error('Error fetching orders', error, { action: 'getOrders', page, status });
        return { data: [], count: 0 };
    }

    return { data, count };
}

